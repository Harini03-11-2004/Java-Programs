public class score {
    public static void main(String[] args) {
        int score = 75;
        if(score>=95)
        {
            System.out.println("Grade : o");
        }
        else if(score>=85)
        {
            System.out.println("Grade : A+");
        }
        else if(score>=70)
        {
            System.out.println("Grade : A");
        }
        else if(score>=65)
        {
            System.out.println("Grade : B+");
        }
        else if(score>=50)
        {
            System.out.println("Grade : B");
        }
        else if(score>=45)
        {
            System.out.println("Grade : c");
        }
        else if(score>=25)
        {
            System.out.println("Grade : D");
        }
        else if(score==0)
        {
            System.out.println("Grade : U");
        }
    }
}
